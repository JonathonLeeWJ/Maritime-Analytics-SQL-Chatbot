def generate_sql(question: str) -> str:
    """STAGE 1: question -> SQL (SELECT only)."""
    prompt = f"""You write SQLite SQL for the database described below.

{SCHEMA}

Example query patterns (adapt to the real tables above, do not copy names literally):
{EXAMPLES}

Rules:
- Return ONLY one valid SQLite SELECT statement. No prose, no markdown fences.
- Read-only: never INSERT/UPDATE/DELETE/DROP/ALTER.
- Use only tables and columns that exist in the schema above.
- Use explicit JOINs on the listed keys. Round money-like numbers to 2 dp and alias columns clearly.

Question: {question}
SQL:"""
    raw = qwen_chat(prompt, max_new_tokens=400)
    raw = re.sub(r"```(?:sql)?", "", raw).replace("```", "").strip()
    m = re.search(r"(select\b.*?)(;|$)", raw, flags=re.IGNORECASE | re.DOTALL)
    return (m.group(1).strip() if m else raw)


def is_safe_select(sql: str) -> bool:
    s = sql.strip().rstrip(";").lower()
    if not s.startswith("select"):
        return False
    banned = ["insert", "update", "delete", "drop", "alter",
              "create", "attach", "pragma", ";"]
    return not any(b in s for b in banned)


def run_sql(sql: str) -> pd.DataFrame:
    con = sqlite3.connect(DB_PATH)
    try:
        return pd.read_sql_query(sql, con)
    finally:
        con.close()


def explain_result(question: str, sql: str, df: pd.DataFrame) -> str:
    """STAGE 3: results -> plain-English answer."""
    preview = df.head(20).to_markdown(index=False)
    prompt = f"""User asked: "{question}"
SQL run:
{sql}
Result (first rows):
{preview}

Write a short, direct plain-English answer. Lead with the key number or finding.
2 to 4 sentences. Do not use em dashes or semicolons."""
    return qwen_chat(prompt, max_new_tokens=300)


def _looks_time(colname: str, sample_value) -> bool:
    """Decide if a column is time-like, so we can draw a line chart."""
    xl = str(colname).lower()
    if any(k in xl for k in ["month", "date", "year", "time",
                             "period", "day", "week", "quarter"]):
        return True
    # value pattern like 2026, 2026-05, or 2026-05-01
    if re.match(r"^\d{4}(-\d{2}){0,2}$", str(sample_value)):
        return True
    return False


def make_chart(df: pd.DataFrame):
    """Pick a chart: line for time-series x, bar otherwise."""
    if df.empty or df.shape[1] < 2:
        return None
    num_cols = [c for c in df.columns if pd.api.types.is_numeric_dtype(df[c])]
    cat_cols = [c for c in df.columns if c not in num_cols]
    if not cat_cols and len(num_cols) >= 2:
        cat_cols = [num_cols[0]]; num_cols = num_cols[1:]
    if not cat_cols or not num_cols:
        return None
    x, y = cat_cols[0], num_cols[0]
    d = df.copy()
    time_like = _looks_time(x, d[x].iloc[0])
    try:
        if time_like:
            d = d.sort_values(by=x)          # order the axis for a sensible line
            fig = px.line(d, x=x, y=y, markers=True, title=f"{y} over {x}")
        else:
            d = d.head(25)
            fig = px.bar(d, x=x, y=y, title=f"{y} by {x}")
        fig.update_layout(xaxis_tickangle=-40, height=460)
        return fig
    except Exception:
        return None


def ask(question: str):
    if not question or not question.strip():
        return "Type a question about your data.", "", pd.DataFrame(), None
    try:
        sql = generate_sql(question)
    except Exception as e:
        return f"Could not generate SQL: {e}", "", pd.DataFrame(), None
    if not is_safe_select(sql):
        return ("For safety I only run read-only SELECT queries, and this did not "
                "produce one. Try rephrasing."), sql, pd.DataFrame(), None
    try:
        df = run_sql(sql)
    except Exception as e:
        return f"SQL failed to run: {e}", sql, pd.DataFrame(), None
    if df.empty:
        return "The query ran but returned no rows.", sql, df, None
    try:
        answer = explain_result(question, sql, df)
    except Exception as e:
        answer = f"(Could not summarise: {e})"
    return answer, sql, df, make_chart(df)


