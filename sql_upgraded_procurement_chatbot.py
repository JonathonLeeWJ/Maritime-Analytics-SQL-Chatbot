def introspect_schema(db_path: str):
    """Read the database's own structure so the bot works on ANY SQLite file.
    Returns (schema_text, list_of_tables)."""
    con = sqlite3.connect(db_path)
    cur = con.cursor()
    tables = [r[0] for r in cur.execute(
        "SELECT name FROM sqlite_master WHERE type='table' "
        "AND name NOT LIKE 'sqlite_%'").fetchall()]
    lines, fks = [], []
    for t in tables:
        cols = cur.execute(f"PRAGMA table_info({t})").fetchall()
        coldesc = ", ".join(f"{c[1]} {c[2]}" for c in cols)
        lines.append(f"{t}({coldesc})")
        for fk in cur.execute(f"PRAGMA foreign_key_list({t})").fetchall():
            fks.append(f"{t}.{fk[3]} = {fk[2]}.{fk[4]}")
    con.close()
    schema = "Tables and columns:\n" + "\n".join(lines)
    if fks:
        schema += "\n\nForeign keys (use these to join):\n" + "\n".join(fks)
    return schema, tables


