def qwen_chat(prompt: str, max_new_tokens: int = 500) -> str:
    """Single-turn helper: send a user prompt, get the text reply."""
    messages = [
        {"role": "system", "content": "You are a precise data assistant."},
        {"role": "user", "content": prompt},
    ]
    text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )
    inputs = tokenizer([text], return_tensors="pt").to(model.device)
    out = model.generate(
        **inputs,
        max_new_tokens=max_new_tokens,
        do_sample=False,        # deterministic -> stabler SQL
        temperature=None, top_p=None, top_k=None,
        pad_token_id=tokenizer.eos_token_id,
    )
    # keep only the newly generated tokens
    gen = out[0][inputs.input_ids.shape[1]:]
    return tokenizer.decode(gen, skip_special_tokens=True).strip()

