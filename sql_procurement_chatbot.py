def ui_ask(question):
    answer, sql, df, fig = ask(question)
    sql_md = f"```sql\n{sql}\n```" if sql else ""
    return answer, sql_md, (df if not df.empty else pd.DataFrame()), fig

with gr.Blocks(title="Maritime Analytics Chatbot (Qwen)") as demo:
    gr.Markdown("## Maritime Analytics Chatbot SQL\n"
                "Ask about crew wages or vessel insurance in plain English. "
                "Qwen writes the SQL, runs it, explains the result, and charts it.")
    with gr.Row():
        q = gr.Textbox(label="Your question", scale=4,
                       placeholder="e.g. average total wage by rank")
